#!/usr/bin/env python3
"""sync-creators.py — ONE SOURCE OF TRUTH for creator data (2026-11-13).

The master DB (src/data/slr-master-db.json) is the only hand-edited
creator file in the system. This script regenerates EVERY consumer of
that data from it, in both repos:

  site repo (this repo):
    1. v1.4.3/core/07-slr-db-data.js  + site/ copy   (bundle snapshot;
       exact formula of build-master-db.py, which is never run for this)
    2. site/sick-left-radicals/index.html            (baked var ROSTER
       array + H1 count + Creators stat + meta counts)
    3. site/sitemap.xml                              (portfolio locs)
    4. build-portfolios.py + build-catalog.py        (invoked; they
       already read the DB directly)
  api repo (~/workspace/mtcstw-api):
    5. src/roster-slugs.generated.js                 (vote allowlist —
       replaces the hand mirror that drifted to 61 slugs)
    6. src/karl-roster.generated.json                (Karl's roster pack,
       for his return; Karl is OFF by CEO order 2026-10-30)

  --pin <sha>: bump the jsDelivr LIVE_DB_URL pin in the 8 carrier files
  to the commit whose tree carries the current DB. Flow for a roster
  change: edit DB -> --write -> commit+push -> --pin <that sha> --write
  -> commit+push -> gate deploy.

Modes: default is --check (report SAME/DIFF per consumer, write
nothing). --write applies, each file via part-file + sha verify +
atomic rename + read-back verify. Fail-closed: a consumer whose
expected patterns are not found aborts that consumer loudly.
"""
import hashlib, json, os, re, subprocess, sys
from datetime import datetime
from zoneinfo import ZoneInfo

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(HERE, '..', '..'))
API = os.path.expanduser('~/workspace/mtcstw-api')
DB_PATH = os.path.join(HERE, 'slr-master-db.json')
WRITE = '--write' in sys.argv
PIN = None
if '--pin' in sys.argv:
    PIN = sys.argv[sys.argv.index('--pin') + 1]

def sha(b): return hashlib.sha256(b).hexdigest()

def safe_write(path, text):
    data = text.encode('utf-8')
    part = '%s.part-%d' % (path, os.getpid())
    with open(part, 'wb') as f: f.write(data)
    if sha(open(part, 'rb').read()) != sha(data):
        os.unlink(part); raise SystemExit('PART VERIFY FAIL: ' + path)
    os.rename(part, path)
    if sha(open(path, 'rb').read()) != sha(data):
        raise SystemExit('READBACK VERIFY FAIL: ' + path)

def report(name, path, new_text):
    old = open(path, encoding='utf-8').read() if os.path.exists(path) else None
    same = (old == new_text)
    print(('SAME ' if same else 'DIFF ') + name + ' -> ' + path)
    if not same and WRITE:
        safe_write(path, new_text); print('     written + verified')
    return same

db = json.load(open(DB_PATH, encoding='utf-8'))
members = db['members']
n = len(members)
today = datetime.now(ZoneInfo('America/Chicago')).strftime('%Y-%m-%d')
results = {}

# 1 — bundle snapshot (build-master-db.py formula, verbatim)
snap = ("/* GENERATED by src/data/build-master-db.py — do not hand-edit. "
        "Rebuild after editing slr-master-db.json. */\n"
        "window.PF_SLR_DB_SNAPSHOT = " + json.dumps(db, ensure_ascii=False) + ";\n")
for p in ['v1.4.3/core/07-slr-db-data.js', 'site/v1.4.3/core/07-slr-db-data.js']:
    results['snapshot'] = report('snapshot', os.path.join(ROOT, p), snap)

# 2 — roster page: baked array + counts
rp_path = os.path.join(ROOT, 'site/sick-left-radicals/index.html')
html = open(rp_path, encoding='utf-8').read()
arr = [{'name': m['name'], 'score': m['propaganda_score'],
        'followers': m['followers_total'], 'platform': m['primary_platform'],
        'bio': (m.get('bio') or '')[:140], 'slug': m['slug']} for m in members]
new_line = 'var ROSTER = ' + json.dumps(arr, ensure_ascii=False) + ';'
html2, k = re.subn(r'var ROSTER = \[.*\];', new_line, html, count=1, flags=re.S)
assert k == 1, 'ROSTER line not found'
html2, k1 = re.subn(r'\d+ vetted propagandists', '%d vetted propagandists' % n, html2)
html2, k2 = re.subn(r'(<div class="n">)\d+(</div><div class="t">Creators</div>)',
                    r'\g<1>%d\g<2>' % n, html2)
h1 = re.search(r'<h1[^>]*>(.*?)</h1>', html2, flags=re.S)
assert h1 and 'radical' in h1.group(1), 'H1 radicals not found'
h1new = re.sub(r'\d+', str(n), h1.group(1), count=1)
html2 = html2[:h1.start(1)] + h1new + html2[h1.end(1):]
print('     roster page: meta x%d, stat x%d, h1 ok' % (k1, k2))
results['roster'] = report('roster page', rp_path, html2)

# 3 — sitemap portfolio locs
sm_path = os.path.join(ROOT, 'site/sitemap.xml')
sm = open(sm_path, encoding='utf-8').read()
blocks = re.findall(r'  <url>\n.*?\n  </url>\n', sm, flags=re.S)
port = [b for b in blocks if re.search(r'<loc>https://www\.mtcstw\.com/@', b)]
assert port, 'no portfolio blocks found in sitemap'
tmpl = port[0]
cf = re.search(r'<changefreq>(.*?)</changefreq>', tmpl).group(1)
pr = re.search(r'<priority>(.*?)</priority>', tmpl).group(1)
new_blocks = ''.join(
    '  <url>\n    <loc>https://www.mtcstw.com/@%s/</loc>\n'
    '    <lastmod>%s</lastmod>\n    <changefreq>%s</changefreq>\n'
    '    <priority>%s</priority>\n  </url>\n' % (m['slug'], today, cf, pr)
    for m in members)
first = sm.index(port[0])
sm2 = sm
for b in port: sm2 = sm2.replace(b, '', 1)
sm2 = sm2[:first] + new_blocks + sm2[first:]
results['sitemap'] = report('sitemap', sm_path, sm2)

# 5 — vote allowlist (api repo)
slugs = sorted(m['slug'] for m in members)
allow = ("/* GENERATED by mtcstw-site-deploy/src/data/sync-creators.py from\n"
         "   slr-master-db.json — do not hand-edit. Replaces the hand mirror\n"
         "   that drifted to 61 slugs (2026-11-13 plumbing pass). */\n"
         "export var ROSTER_SLUGS_GENERATED = {\n" +
         ''.join("  '%s': 1,\n" % s for s in slugs) + "};\n")
results['allowlist'] = report('vote allowlist',
    os.path.join(API, 'src/roster-slugs.generated.js'), allow)

# 6 — Karl roster pack (api repo; consumed when Karl returns)
pack = [{'slug': m['slug'], 'name': m['name'],
         'score': m['propaganda_score'], 'followers_total': m['followers_total'],
         'primary_platform': m['primary_platform'],
         'handles': m.get('handles', {})} for m in members]
results['karlpack'] = report('karl pack',
    os.path.join(API, 'src/karl-roster.generated.json'),
    json.dumps(pack, ensure_ascii=False, indent=1) + '\n')

# pin bump (8 carrier files)
if PIN:
    pat = re.compile(r'(cdn\.jsdelivr\.net/gh/swananas/MTCSTW-site-deploy@)[0-9a-f]+')
    carriers = ['v1.4.3/core/07-slr-db.js', 'v1.4.3/core/15-seo.js',
                'v1.4.3/core/bundle-core.js', 'v1.4.3/core/bundle-core-slr.js',
                'site/v1.4.3/core/07-slr-db.js', 'site/v1.4.3/core/15-seo.js',
                'site/v1.4.3/core/bundle-core.js', 'site/v1.4.3/core/bundle-core-slr.js']
    for rel in carriers:
        p = os.path.join(ROOT, rel)
        t = open(p, encoding='utf-8').read()
        t2, k = pat.subn(r'\g<1>' + PIN, t)
        print('     pin x%d in %s' % (k, rel))
        results['pin:' + rel] = report('pin', p, t2)

# 4 — DB-native generators (invoked, not reimplemented)
if WRITE:
    for script in ['build-portfolios.py', 'build-catalog.py']:
        r = subprocess.run([sys.executable, script], cwd=ROOT,
                           capture_output=True, text=True)
        print('%s: exit %d %s' % (script, r.returncode,
              (r.stdout.strip().split('\n')[-1] if r.stdout.strip() else '')))
        if r.returncode != 0:
            print(r.stderr[-2000:]); raise SystemExit('GENERATOR FAILED: ' + script)
    # build-portfolios.py also emits untracked legacy mirrors at
    # site/<slug>/ — the committed tree carries only site/@<slug>/.
    # Remove the mirrors for member slugs (never a tracked path).
    tracked = subprocess.run(['git', 'ls-files', 'site'], cwd=ROOT,
                             capture_output=True, text=True).stdout
    for m in members:
        d = os.path.join(ROOT, 'site', m['slug'])
        if os.path.isdir(d) and ('site/%s/' % m['slug']) not in tracked:
            subprocess.run(['rm', '-rf', d]); print('cleaned legacy mirror site/' + m['slug'])

print('\n%d members | consumers SAME: %s' %
      (n, ', '.join(k for k, v in results.items() if v) or 'none'))
if not WRITE:
    print('check mode — nothing written. Re-run with --write to apply.')
