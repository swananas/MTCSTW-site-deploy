#!/usr/bin/env node
/* scripts/verify-phq-share-consolidation.js
   QC gate for the share-painter consolidation (fe/phq-share-consolidation).
   Static checks + headless functional checks (mocked DOM/canvas).
   Exit 0 = pass, 1 = fail. Run from the repo root. */
'use strict';
var fs = require('fs');
var path = require('path');
var child = require('child_process');

var ROOT = path.resolve(__dirname, '..');
var failures = [];
function check(name, cond, detail) {
  console.log((cond ? 'PASS' : 'FAIL') + '  ' + name + (cond ? '' : '  :: ' + (detail || '')));
  if (!cond) failures.push(name);
}
function read(p) { return fs.readFileSync(path.join(ROOT, p), 'utf8'); }
function grepFiles(re, exts) {
  var out = child.execSync('git grep -l -E ' + JSON.stringify(re.source) + ' -- ' +
    exts.map(function (e) { return JSON.stringify('**/*' + e); }).join(' ') + ' || true',
    { cwd: ROOT, encoding: 'utf8' });
  return out.split('\n').filter(Boolean);
}

var MOD = 'v1.4.3/core/share-image-phq.js';
var STUB = 'v1.4.3/core/share-image-phq-lazy.js';
var modSrc = read(MOD), stubSrc = read(STUB);

/* ---- 1. No reassignment of the facade outside the two canonical files ----
   Built bundle artifacts (v1.4.3 bundle dash js files) are excluded: they are
   regenerated by Release Eng from build/bundle-core.js, and the stale
   checked-in copies still carry the pre-consolidation reassignment until
   the rebuild lands. */
var assigners = grepFiles(/PF\.PHQShare\s*=/, ['.js'])
  .filter(function (f) { return f !== MOD && f !== STUB && f.indexOf('/bundle-') === -1; });
check('no PF.PHQShare= outside canonical files', assigners.length === 0, assigners.join(', '));
var staleBundle = (read('v1.4.3/pages/bundle-pages.js').match(/PF\.PHQShare = \{/g) || []).length > 0;
console.log('INFO  built v1.4.3/pages/bundle-pages.js still carries the old reassignment: ' +
  staleBundle + ' (Release Eng rebuilds it from build/bundle-core.js on merge)');
/* The two canonical files each assign exactly once, guarded. */
check('module assigns facade once (standalone guard)',
  (modSrc.match(/PF\.PHQShare = /g) || []).length === 1);
check('stub assigns facade once (bundle path)',
  (stubSrc.match(/PF\.PHQShare = /g) || []).length === 1);
check('module kill check is first executable line',
  /var PF = window\.PF;\s*\n\s*if \(PF && PF\.skip\('phq-share'\)\) \{ return; \}/.test(modSrc));
check('stub kill check is first executable line',
  /var PF = window\.PF;\s*\n\s*if \(PF && PF\.skip\('phq-share'\)\) \{ return; \}/.test(stubSrc));

/* ---- 2. kits module retired ---- */
var kits = child.execSync("git ls-files | grep -E 'share-image-phq-kits' || true", { cwd: ROOT, encoding: 'utf8' }).trim();
check('share-image-phq-kits.js retired', kits === '', kits);

/* ---- 3. Bundle wiring: stub in, module out (lazy-load is load-bearing) ---- */
var cfg = read('build/bundle-core.js');
check('stub in pages/bundle-pages bundle', cfg.indexOf("'core/share-image-phq-lazy.js'") !== -1);
check('full module NOT in any bundle list',
  !/'core\/share-image-phq\.js'/.test(cfg),
  'module must lazy-load, never bundle');

/* ---- 4. Registry shape ---- */
check('module exposes registerPainters', /registerPainters/.test(modSrc));
check('module never calls PF.PHQShare = unconditionally',
  !/^\s*PF\.PHQShare = \{/m.test(modSrc));
var EXPECTED = ['phq-pressure', 'phq-prediction', 'phq-predict-call', 'phq-scorecard',
  'phq-cellwin', 'phq-ballot', 'phq-pledge', 'phq-racecall', 'phq-race', 'phq-wallshame',
  'phq-pac', 'phq-trades', 'phq-bill-status', 'phq-nonprofit', 'phq-poll-results',
  'phq-rep-contact', 'phq-money', 'phq-ledger', 'phq-boycott', 'phq-corp',
  'phq-votedonor', 'phq-bill', 'phq-urgency'];
var missing = EXPECTED.filter(function (id) { return modSrc.indexOf("'" + id + "'") === -1; });
check('all 23 painter ids present', missing.length === 0, missing.join(', '));
/* Every id a silo references must resolve. */
var refs = {};
grepFiles(/PHQShare\.(share|save|paint)\(\s*['"]phq-[a-z-]+['"]/, ['.js']).forEach(function (f) {
  var s = read(f), m, re = /PHQShare\.(?:share|save|paint)\(\s*['"](phq-[a-z-]+)['"]/g;
  while ((m = re.exec(s))) refs[m[1]] = true;
});
var unreg = Object.keys(refs).filter(function (id) { return EXPECTED.indexOf(id) === -1; });
check('every silo-referenced painter id is registered', unreg.length === 0, unreg.join(', '));

/* ---- 5. Headless functional checks ---- */
function makeEnv() {
  function Ctx() {}
  ['fillRect', 'strokeRect', 'fillText', 'measureText', 'save', 'restore', 'translate',
   'rotate', 'fill', 'stroke', 'beginPath', 'closePath', 'moveTo', 'lineTo', 'arc',
   'clearRect', 'drawImage', 'setLineDash'].forEach(function (m) {
    Ctx.prototype[m] = function () { return m === 'measureText' ? { width: 10 } : undefined; };
  });
  function mkCanvas() { return { width: 0, height: 0, getContext: function () { return new Ctx(); } }; }
  var appended = [];
  var g = {
    document: {
      createElement: function (t) {
        if (t === 'canvas') return mkCanvas();
        return { async: false, set src(v) { this._src = v; }, get src() { return this._src; } };
      },
      getElementsByTagName: function () {
        return [{ src: 'https://cdn.jsdelivr.net/gh/swananas/MTCSTW-site-deploy@PIN/v1.4.3/pages/bundle-pages.js' }];
      },
      head: { appendChild: function (s) { appended.push(s.src); } }
    },
    localStorage: { getItem: function () { return '{}'; }, setItem: function () {} },
    console: console
  };
  g.window = g;
  g.window.PF = { skip: function () { return false; }, toast: function () {} };
  var shared = [];
  g.window.PFShare = {
    setPoster: function () {},
    shareImage: function (cv, fn, title, id, opts) { shared.push({ kind: 'share', id: id }); },
    saveImage: function (cv, fn, id, opts) { shared.push({ kind: 'save', id: id }); },
    stampCallsign: function () {}
  };
  return { g: g, appended: appended, shared: shared };
}
function runIn(env, src) {
  var fn = new Function('window', 'document', 'localStorage', 'console', src);
  fn.call(env.g, env.g, env.g.document, env.g.localStorage, env.g.console);
}
(function functional() {
  var env = makeEnv();
  runIn(env, modSrc);
  var F = env.g.PF.PHQShare;
  check('facade created with 23 ids', !!F && F.ids.length === 23, F && F.ids.length);
  var painted = 0, nulled = [];
  var SAMPLE = {
    'phq-pledge': { stateCode: 'TX', stateName: 'Texas', deadline: '2026-11-03', daysLeft: 29, registerUrl: 'x', electionDay: 'Nov 3', source: 's' }
  };
  F.ids.forEach(function (id) {
    var d = SAMPLE[id] || { title: 'T', state: 'TX', daysLeft: 3 };
    if (F.paint(id, d)) painted++; else nulled.push(id);
  });
  check('painters render with representative data', painted === 23, 'null: ' + nulled.join(','));
  check('unknown id: share=false', F.share('phq-nope', {}) === false);
  check('unknown id: paint=null', F.paint('phq-nope', {}) === null);
  /* per-painter kill */
  var env2 = makeEnv();
  env2.g.PF.skip = function (id) { return id === 'phq-pac'; };
  runIn(env2, modSrc);
  var F2 = env2.g.PF.PHQShare;
  check('?pf_off=phq-pac excludes that painter only',
    F2.ids.indexOf('phq-pac') === -1 && F2.ids.length === 22 && F2.share('phq-pac', {}) === false);
  /* module kill */
  var env3 = makeEnv();
  env3.g.PF.skip = function () { return true; };
  runIn(env3, modSrc);
  check('?pf_off=phq-share kills module', !env3.g.PF.PHQShare);
  /* lazy flow: stub queues, module replays */
  var env4 = makeEnv();
  runIn(env4, stubSrc);
  var S = env4.g.PF.PHQShare;
  var queued = S.share('phq-pressure', { title: 'T' });
  var injected = env4.appended[0];
  runIn(env4, modSrc);
  check('stub queues share + injects versioned module URL',
    queued === true && /\/v1\.4\.3\/core\/share-image-phq\.js$/.test(injected || ''), injected);
  check('queued share replays after module load',
    env4.shared.length === 1 && env4.shared[0].id === 'phq-pressure');
  check('same facade object before/after module load', env4.g.PF.PHQShare === S);
  check('double module load is idempotent', (function () {
    var n = S.ids.length; runIn(env4, modSrc); return S.ids.length === n;
  })());
})();

console.log(failures.length ? '\nRESULT: FAIL (' + failures.length + ')' : '\nRESULT: PASS');
process.exit(failures.length ? 1 : 0);
