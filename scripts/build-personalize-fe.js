#!/usr/bin/env node
/* scripts/build-personalize-fe.js — rebuild ONLY pages/bundle-pages with the
   canonical pipeline (fe/home-personalize). Parses the file list OUT of
   build/bundle-core.js (BUNDLES) so registration drift is impossible.
   Run from the worktree root: node scripts/build-personalize-fe.js
   Bundle: v1.4.3/pages/bundle-pages.js */
'use strict';
var fs = require('fs');
var path = require('path');
var cp = require('child_process');

var ROOT = path.join(__dirname, '..');
var V143 = path.join(ROOT, 'v1.4.3');

/* File list for a BUNDLES entry in build/bundle-core.js. */
function coreFiles(name) {
  var src = fs.readFileSync(path.join(ROOT, 'build', 'bundle-core.js'), 'utf8');
  var idx = src.indexOf("'" + name + "'");
  if (idx < 0) throw new Error('bundle entry not found: ' + name);
  idx = src.indexOf('[', idx);
  var end = src.indexOf('],', idx);
  if (end < 0) throw new Error('bundle entry unterminated: ' + name);
  var block = src.slice(idx, end);
  var files = [], re = /'([a-z0-9\-\/]+\.js)'/g, m;
  while ((m = re.exec(block))) {
    if (files.indexOf(m[1]) === -1) files.push(m[1]);
  }
  return files;
}

var TERSER = null;
var candidates = [
  path.join(ROOT, 'node_modules', '.bin', 'terser'),
  '/tmp/terser-fix/node_modules/.bin/terser'
];
for (var ci = 0; ci < candidates.length; ci++) {
  try { cp.execSync(candidates[ci] + ' --version', { stdio: 'pipe' }); TERSER = candidates[ci]; break; }
  catch (e) {}
}
if (!TERSER) { console.error('BUNDLE FAIL: no working terser'); process.exit(1); }

function build(name, dir, files) {
  var out = [];
  out.push('/* PF v1.4.3 ' + name + '.js — concatenated bundle, generated by build scripts.');
  out.push('   DO NOT EDIT. Regenerate with the canonical bundle pipeline.');
  out.push('   Contains: ' + files.join(', '));
  out.push('   Each silo keeps its own PF.skip() kill switch (?pf_off=<silo>). */');
  files.forEach(function (f) {
    var p = path.join(dir, f);
    if (!fs.existsSync(p)) { console.error('BUNDLE FAIL: missing ' + f); process.exit(1); }
    out.push('\n/* ===== ' + f + ' ===== */');
    out.push(fs.readFileSync(p, 'utf8'));
    out.push(';');
  });
  var dest = path.join(dir, name + '.js');
  var raw = out.join('\n');
  var final;
  try {
    final = cp.execSync(TERSER + ' --compress --mangle --toplevel', {
      input: raw, maxBuffer: 100 * 1024 * 1024
    }).toString();
  } catch (e) {
    console.error('BUNDLE FAIL: terser failed on ' + name + ': ' + (e.message || e));
    process.exit(1);
  }
  fs.writeFileSync(dest, final);
  try { cp.execSync('node --check ' + dest, { stdio: 'pipe' }); }
  catch (e) { console.error('BUNDLE FAIL: ' + name + ' node --check'); process.exit(1); }
  try { new Function(fs.readFileSync(dest, 'utf8')); }
  catch (e) { console.error('BUNDLE FAIL: ' + name + ' parse: ' + e.message); process.exit(1); }
  var bytes = fs.statSync(dest).size;
  var saved = Math.round((1 - final.length / raw.length) * 100);
  console.log(name + '.js: ' + (bytes / 1024).toFixed(1) + ' KB (' + saved + '% smaller) — OK');
}

/* NOTE: name carries the subdir (canonical convention), so dest lands at
   v1.4.3/pages/bundle-pages.js. */
build('pages/bundle-pages', V143, coreFiles('pages/bundle-pages'));
