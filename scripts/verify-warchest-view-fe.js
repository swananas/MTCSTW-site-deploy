function coreFilesFromBuildScript() {
  var bsrc = read(path.join(ROOT, 'build', 'bundle-core.js'));
  var m = /var CORE_FILES = \[([\s\S]*?)\n\];/.exec(bsrc);
  if (!m) throw new Error('CORE_FILES block not found');
  var files = [];
  var re = /'(core\/[^']+\.js)'/g, mm;
  while ((mm = re.exec(m[1]))) files.push(mm[1]);
  return files;
}
function writeCoreBundle(name, files) {
  var out = [];
  out.push('/* PF v1.4.3 ' + name + '.js — concatenated bundle, generated by build/bundle-core.js.');
  out.push('   DO NOT EDIT. Regenerate with: node build/bundle-core.js [--debug]');
  out.push('   Contains: ' + files.join(', '));
  out.push('   Each file keeps its own PF.skip() kill switch (?pf_off=<silo>). */');
  files.forEach(function (f) {
    var p = path.join(V, f);
    if (!fs.existsSync(p)) throw new Error('missing file: ' + f);
    out.push('\n/* ===== ' + f + ' ===== */');
    out.push(read(p));
    out.push(';');
  });
  var raw = out.join('\n');
  var final = raw;
  try {
    final = cp.execSync('node_modules/.bin/terser --compress --mangle --toplevel',
      { input: raw, maxBuffer: 100 * 1024 * 1024 }).toString();
  } catch (e) { /* raw fallback, same as the real build */ }
  var dest = path.join(V, name + '.js');
  fs.writeFileSync(dest, final);
  cp.execSync('node --check ' + dest, { stdio: 'pipe' });
}
